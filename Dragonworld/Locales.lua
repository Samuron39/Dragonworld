local current = DEFAULT
local listeners = {}

-- DW.L.NAVN gir teksten på valgt språk. Finnes den ikke der, brukes engelsk.
-- Finnes den ikke i det hele tatt, vises navnet, så feilen er lett å se.
DW.L = setmetatable({}, {
    __index = function(_, key)
        return strings[current][key] or strings[DEFAULT][key] or key
    end,
})

function DW.GetLanguage()
    return current
end

-- Har spilleren valgt språk selv? Hvis ikke, spør hovedvinduet første gang.
function DW.HasChosenLanguage()
    return type(DragonworldDB) == "table" and strings[DragonworldDB.language] ~= nil
end

-- Registrerer en funksjon som kalles hver gang språket byttes, slik at
-- vinduer kan skrive teksten sin på nytt.
function DW.OnLanguageChanged(callback)
    listeners[#listeners + 1] = callback
end

-- Bytter språk for hele addonen. Med save = true huskes valget til neste gang.
function DW.SetLanguage(code, save)
    if not strings[code] then
        return false
    end
    current = code
    if save and type(DragonworldDB) == "table" then
        DragonworldDB.language = code
    end
    for _, callback in ipairs(listeners) do
        local ok, problem = pcall(callback)
        if not ok then
            print("|cff33ff99Dragonworld:|r |cffff5555" .. DW.L.ERROR .. "|r " .. tostring(problem))
        end
    end
    return true
end
