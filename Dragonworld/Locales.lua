-- Dragonworld - language
--
-- All text the player sees is here, in English (en), Norwegian (nb), Dutch
-- (nl), German (de), Danish (da), Swedish (sv) and French (fr). The rest of
-- the addon gets text like this:  DW.L.NAME
--
-- To add a new text: give it a name and write it into every table below. If
-- it is missing in a language, the English one is shown.
-- Texts for a module start with the module's abbreviation (RS_ = Ryddesekk).
--
-- The game has no Norwegian, Dutch, Danish or Swedish client, so the language
-- can't be guessed. The player chooses the first time the main window opens,
-- and can change it under Settings. Until then English is used.

